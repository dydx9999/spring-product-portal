WITH
    duplicate_cart_items AS (
        SELECT
            user_id,
            product_id,
            MIN(id) AS keep_id,
            CAST(SUM(quantity) AS INTEGER) AS total_quantity
        FROM
            cart
        GROUP BY
            user_id,
            product_id
        HAVING
            COUNT(*) > 1
    )
UPDATE cart AS c
SET
    quantity = duplicates.total_quantity
FROM
    duplicate_cart_items AS duplicates
WHERE
    c.id = duplicates.keep_id;

DELETE FROM cart AS c USING (
    SELECT
        user_id,
        product_id,
        MIN(id) AS keep_id
    FROM
        cart
    GROUP BY
        user_id,
        product_id
    HAVING
        COUNT(*) > 1
) AS duplicates
WHERE
    c.user_id = duplicates.user_id
    AND c.product_id = duplicates.product_id
    AND c.id <> duplicates.keep_id;

CREATE UNIQUE INDEX IF NOT EXISTS uq_cart_user_product ON cart (user_id, product_id);

-- Listed products by vendor
CREATE TABLE
    IF NOT EXISTS vendor_products_listed (
        vendor_pk BIGINT NOT NULL,
        list_position INTEGER NOT NULL,
        product_sku VARCHAR(255),
        PRIMARY KEY (vendor_pk, list_position),
        FOREIGN KEY (vendor_pk) REFERENCES vendors (id)
    );

CREATE TABLE
    IF NOT EXISTS order_items (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_id BIGINT NOT NULL REFERENCES orders (id),
        product_price DECIMAL(19, 2) NOT NULL,
        product_name VARCHAR(255) NOT NULL,
        product_quantity INTEGER NOT NULL
    );

CREATE TABLE
    IF NOT EXISTS reviews (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_item_id BIGINT NOT NULL REFERENCES order_items (id),
        buyer_id BIGINT NOT NULL REFERENCES users (id),
        rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE (order_item_id, buyer_id)
    );