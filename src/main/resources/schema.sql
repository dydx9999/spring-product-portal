-- Matches Product.java entity (default Hibernate snake_case naming, no @Column overrides)
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(255) NOT NULL,
    product_price DECIMAL(19, 2) NOT NULL,
    available_quantity INTEGER NOT NULL,
    product_sku VARCHAR(255) NOT NULL,
    vendor_notes VARCHAR(255),
    vendor_name VARCHAR(255)
);

-- CREATE TABLE IF NOT EXISTS skips a table already persisted in the H2 file, so add the column explicitly
ALTER TABLE products ADD COLUMN IF NOT EXISTS vendor_name VARCHAR(255);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    balance DECIMAL(19, 2),
    creation_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cart (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (product_id) REFERENCES products(id)
);


ALTER TABLE users ADD COLUMN IF NOT EXISTS role VARCHAR(50) DEFAULT 'USER' NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS creation_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT,
    total_sales_count INTEGER,
    total_sales_revenue DECIMAL(19, 2)
);

CREATE TABLE IF NOT EXISTS vendor_products_listed (
    vendor_pk BIGINT NOT NULL,
    list_position INTEGER NOT NULL,
    product_sku VARCHAR(255),
    PRIMARY KEY (vendor_pk, list_position),
    FOREIGN KEY (vendor_pk) REFERENCES vendors(id)
);

CREATE TABLE IF NOT EXISTS vendor_feedback (
    vendor_pk BIGINT NOT NULL,
    feedback_type VARCHAR(255) NOT NULL,
    feedback_count INTEGER,
    PRIMARY KEY (vendor_pk, feedback_type),
    FOREIGN KEY (vendor_pk) REFERENCES vendors(id)
);





